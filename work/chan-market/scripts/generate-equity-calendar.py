"""Generate offline regular-session calendars. Run with exchange-calendars==4.13.3.

Coverage is explicit. Do not extend XSHG into an unannounced holiday year.
2026 schedule cross-checks:
https://www.sse.com.cn/disclosure/announcement/general/c/c_20251222_10802507.shtml
https://www.szse.cn/English/services/trading/calendar/index.html
https://www.nyse.com/trade/hours-calendars
"""
import json
from importlib.metadata import version
from pathlib import Path

import exchange_calendars as exchanges
import pandas as pd


def snapshot(name, end):
    start = "2000-01-01"
    calendar = exchanges.get_calendar(name, start=start, end=end)
    regular = calendar.schedule
    layouts = [[]]
    years = {}
    for date in pd.date_range(start, end, freq="D"):
        segments = []
        if date in regular.index:
            times = regular.loc[date]
            boundaries = [times.open, times.break_start, times.break_end, times.close]
            local = [t.tz_convert(calendar.tz) for t in boundaries if not pd.isna(t)]
            minutes = [t.hour * 60 + t.minute for t in local]
            segments = [{"start": a, "end": b} for a, b in zip(minutes[::2], minutes[1::2])]
        if segments not in layouts:
            layouts.append(segments)
        index = layouts.index(segments)
        assert index < 10
        years[date.year] = years.get(date.year, "") + str(index)
    return dict(start=start, end=end, layouts=layouts, years=years)


if __name__ == "__main__":
    if version("exchange-calendars") != "4.13.3":
        raise RuntimeError("Install exchange-calendars==4.13.3 before regenerating.")
    calendars = {"cn": snapshot("XSHG", "2026-12-31"), "hk": snapshot("XHKG", "2026-12-31"), "us": snapshot("XNYS", "2028-12-31")}
    text = "// Generated by scripts/generate-equity-calendar.py with exchange-calendars 4.13.3.\n"
    text += "// Each digit, starting January 1, selects a session layout. Zero denotes a closed date.\n"
    text += "export const equityCalendarData=" + json.dumps(calendars, indent=2) + ";\n"
    (Path(__file__).resolve().parents[1] / "lib/equity-calendar-data.ts").write_bytes(text.encode())
